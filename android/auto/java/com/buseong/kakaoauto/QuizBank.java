    /** 문제 수 */
    public static int size() {
        return Q.length;
    }

    /** 랜덤 문제 번호 */
    public static int randomIndex() {
        if (Q.length == 0) return -1;
        return RND.nextInt(Q.length);
    }

    /** 이미 낸 번호를 피해서 랜덤 문제 번호 (다 돌았으면 아무거나) */
    public static int randomIndex(java.util.Set<Integer> skip) {
        if (Q.length == 0) return -1;
        if (skip == null || skip.size() >= Q.length) return randomIndex();
        for (int i = 0; i < 80; i++) {
            int n = RND.nextInt(Q.length);
            if (!skip.contains(Integer.valueOf(n))) return n;
        }
        for (int n = 0; n < Q.length; n++) {
            if (!skip.contains(Integer.valueOf(n))) return n;
        }
        return randomIndex();
    }

    public static boolean valid(int i) {
        return i >= 0 && i < Q.length && Q[i] != null && Q[i].length >= 3;
    }

    public static String question(int i) {
        return valid(i) ? Q[i][0] : "";
    }

    public static String answer(int i) {
        return valid(i) ? Q[i][1] : "";
    }

    public static String hint(int i) {
        return valid(i) ? Q[i][2] : "";
    }

    /**
     * 사용자 답이 맞았나. 공백·대소문자·문장부호를 무시한다.
     * 정답이 두 글자를 넘으면 그 안에 들어있는 짧은 답도 인정한다("세종대왕" ← "세종").
     */
    public static boolean correct(int i, String given) {
        if (!valid(i)) return false;
        String a = norm(answer(i));
        String g = norm(given);
        if (a.length() == 0 || g.length() == 0) return false;
        if (a.equals(g)) return true;
        if (g.length() >= 2 && a.length() > g.length() && a.contains(g)) return true;
        // "10월 9일" 처럼 공백이 들어간 정답은 norm 에서 공백이 빠져 이미 맞춰진다.
        // 반대로 사용자가 정답보다 길게 쓴 경우("정답은 서울") 도 받아준다.
        if (a.length() >= 2 && g.length() > a.length() && g.contains(a)) return true;
        return false;
    }

    /** 비교용 정규화: 공백·문장부호 제거 + 소문자 */
    public static String norm(String s) {
        if (s == null) return "";
        StringBuilder sb = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (Character.isWhitespace(c)) continue;
            if (c == '.' || c == ',' || c == '!' || c == '?' || c == '\'' || c == '"'
                    || c == '·' || c == '~' || c == '-' || c == '_' || c == '(' || c == ')') continue;
            sb.append(c);
        }
        return sb.toString().toLowerCase(Locale.getDefault());
    }
